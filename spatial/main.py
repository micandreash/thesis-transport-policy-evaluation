import os

from indicators.accessibility import AccessibilityAnalyzer
from indicators.accidents import AccidentsAnalyzer
from indicators.emissions import EmissionsAnalyzer
from indicators.noise import NoiseAnalyzer
from indicators.total_externalities import TotalExternalitiesAnalyzer


def main() :
    print("=" * 60)
    print("MATSim Spatial Policy Assessment Pipeline - Munich")
    print("=" * 60)

    # -----------------------------------------------------------------------
    # 1. CENTRAL CONFIGURATION & PATHS
    # -----------------------------------------------------------------------
    # Base Data Directory
    BASE_DIR = r"C:\Users\hutab\LRZ Sync+Share\Thesis\data"
    OUT_BASE = os.path.join(BASE_DIR, r"final_results_OOP")

    # Common Files
    STADTBEZIRKE = os.path.join(BASE_DIR, r"stadtbezirke\final_stadtbezirke_munich_v2.json")
    NETWORK = os.path.join(BASE_DIR, r"eqasim_population_bavaria\final_munich_1pct_network_connected.xml.gz")

    # Accessibility Paths
    ACC_BEFORE = os.path.join(BASE_DIR, r"final_indicators\accessibility_munich\null\accessibilities.csv")
    ACC_AFTER = os.path.join(BASE_DIR, r"final_indicators\accessibility_altstadt\null\accessibilities.csv")
    ACC_OUT = os.path.join(OUT_BASE, r"spatial_accessibility")

    # Accidents Paths
    ACD_INFO_B = os.path.join(BASE_DIR, r"final_indicators\accidents_munich\ITERS\it.0\null.0.linkInfo.csv")
    ACD_COST_B = os.path.join(BASE_DIR, r"final_indicators\accidents_munich\ITERS\it.0\null.0.accidentCosts_BVWP.csv")
    ACD_INFO_A = os.path.join(BASE_DIR, r"final_indicators\accidents_altstadt\ITERS\it.0\null.0.linkInfo.csv")
    ACD_COST_A = os.path.join(BASE_DIR, r"final_indicators\accidents_altstadt\ITERS\it.0\null.0.accidentCosts_BVWP.csv")
    ACD_OUT = os.path.join(OUT_BASE, r"spatial_accidents")

    # Emissions Paths
    EMI_BEFORE = os.path.join(BASE_DIR,
                              r"final_indicators\emissions_munich (some agents need to be filtered)\output_emission_events.xml.gz")
    EMI_AFTER = os.path.join(BASE_DIR,
                             r"final_indicators\emissions_altstadt (some agents need to be filtered)\output_emission_events.xml.gz")
    EMI_OUT = os.path.join(OUT_BASE, r"spatial_emissions")

    # Noise Paths
    NOI_DIR_B = os.path.join(BASE_DIR,
                             r"final_indicators\noise_munich_ignore_pt_all_activities\run3\noise-analysis\damages_receiverPoint")
    NOI_DIR_A = os.path.join(BASE_DIR,
                             r"final_indicators\noise_altstadt_ignore_pt_all_activities\run3\noise-analysis\damages_receiverPoint")
    NOI_OUT = os.path.join(OUT_BASE, r"spatial_noise")

    # Total Externalities Output
    TOT_OUT = os.path.join(OUT_BASE, r"spatial_externalities_combined")

    # -----------------------------------------------------------------------
    # 2. EXECUTION CONTROL
    # -----------------------------------------------------------------------
    RUN_ACCESSIBILITY = True
    RUN_ACCIDENTS = True
    RUN_EMISSIONS = True
    RUN_NOISE = True
    RUN_TOTAL_EXT = True

    # -----------------------------------------------------------------------
    # 3. PIPELINE EXECUTION
    # -----------------------------------------------------------------------

    if RUN_ACCESSIBILITY :
        print("\n>>> Starting Accessibility Pipeline...")
        acc_analyzer = AccessibilityAnalyzer(ACC_BEFORE, ACC_AFTER, STADTBEZIRKE, ACC_OUT)
        acc_analyzer.run_pipeline()

    if RUN_ACCIDENTS :
        print("\n>>> Starting Accidents Pipeline...")
        acd_analyzer = AccidentsAnalyzer(NETWORK, ACD_INFO_B, ACD_COST_B, ACD_INFO_A, ACD_COST_A, STADTBEZIRKE, ACD_OUT)
        acd_analyzer.run_pipeline()

    if RUN_EMISSIONS :
        print("\n>>> Starting Emissions Pipeline...")
        emi_analyzer = EmissionsAnalyzer(EMI_BEFORE, EMI_AFTER, NETWORK, STADTBEZIRKE, EMI_OUT)
        emi_analyzer.run_pipeline()

    if RUN_NOISE :
        print("\n>>> Starting Noise Pipeline...")
        # Noise assumes Receiver Points coordinates are identical to Accessibility coords
        noi_analyzer = NoiseAnalyzer(ACC_BEFORE, NOI_DIR_B, NOI_DIR_A, STADTBEZIRKE, NOI_OUT)
        noi_analyzer.run_pipeline()

    if RUN_TOTAL_EXT :
        print("\n>>> Starting Total Externalities Pipeline (100% Population Scaling)...")
        # Define the dictionary of output files generated by the previous steps
        total_paths = {
            "accidents" : {
                "bezirke" : os.path.join(ACD_OUT, "accidents_aggregated_bezirke.csv"),
                "grid" : os.path.join(ACD_OUT, "accidents_aggregated_grid.csv"),
                "hexagon" : os.path.join(ACD_OUT, "accidents_aggregated_hex.csv")
            },
            "emissions" : {
                "bezirke" : os.path.join(EMI_OUT, "emissions_aggregated_bezirke.csv"),
                "grid" : os.path.join(EMI_OUT, "emissions_aggregated_grid.csv"),
                "hexagon" : os.path.join(EMI_OUT, "emissions_aggregated_hex.csv")
            },
            "noise" : {
                "bezirke" : os.path.join(NOI_OUT, "noise_aggregated_bezirke.csv"),
                "grid" : os.path.join(NOI_OUT, "noise_aggregated_grid.csv"),
                "hexagon" : os.path.join(NOI_OUT, "noise_aggregated_hex.csv")
            }
        }

        tot_analyzer = TotalExternalitiesAnalyzer(total_paths, STADTBEZIRKE, TOT_OUT, population_scale=100.0)
        tot_analyzer.run_pipeline()

    print("\n" + "=" * 60)
    print("ALL REQUESTED PIPELINES EXECUTED SUCCESSFULLY.")
    print("=" * 60)


if __name__ == "__main__" :
    main()