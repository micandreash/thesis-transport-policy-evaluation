import os

from indicators.accessibility import AccessibilityAgentAnalyzer
from indicators.accidents import AccidentsAgentAnalyzer
from indicators.emissions import EmissionsAgentAnalyzer
from indicators.net_welfare import NetWelfareAnalyzer
from indicators.noise import NoiseAgentAnalyzer


def main() :
    print("=" * 70)
    print("MATSim Socio-Demographic (Agent-Level) Policy Assessment Pipeline")
    print("=" * 70)

    # -----------------------------------------------------------------------
    # 1. CENTRAL CONFIGURATION & PATHS
    # -----------------------------------------------------------------------
    BASE_DIR = r"C:\Users\hutab\LRZ Sync+Share\Thesis\data"

    # Common Input Files
    PLANS_BASE = os.path.join(BASE_DIR, r"eqasim_population_bavaria\final_munich_1pct_population.xml.gz")
    NETWORK_XML = os.path.join(BASE_DIR, r"eqasim_population_bavaria\final_munich_1pct_network_connected.xml.gz")

    # Outputs Directory Base
    OUT_BASE = os.path.join(BASE_DIR, r"final_results_OOP")

    # --- ACCESSIBILITY PATHS ---
    ACC_BEFORE_CSV = os.path.join(BASE_DIR,
                                  r"eqasim_population_bavaria\final_simulation_output_munich\dmc_utilities.csv")
    ACC_AFTER_CSV = os.path.join(BASE_DIR,
                                 r"eqasim_population_bavaria\final_simulation_output_altstadt\dmc_utilities.csv")
    OUT_ACC = os.path.join(OUT_BASE, r"sociodemo_accessibility")

    # --- ACCIDENTS PATHS ---
    ACD_EVENTS_B = os.path.join(BASE_DIR,
                                r"eqasim_population_bavaria\final_simulation_output_munich\ITERS\it.121\121.events.xml.gz")
    ACD_EVENTS_A = os.path.join(BASE_DIR,
                                r"eqasim_population_bavaria\final_simulation_output_altstadt\ITERS\it.116\116.events.xml.gz")
    OUT_ACD = os.path.join(OUT_BASE, r"sociodemo_accidents")

    # --- EMISSIONS PATHS ---
    EMI_EVENTS_B = os.path.join(BASE_DIR,
                                r"final_indicators\emissions_munich (some agents need to be filtered)\output_emission_events.xml.gz")
    EMI_EVENTS_A = os.path.join(BASE_DIR,
                                r"final_indicators\emissions_altstadt (some agents need to be filtered)\output_emission_events.xml.gz")
    OUT_EMI = os.path.join(OUT_BASE, r"sociodemo_emissions")

    # --- NOISE PATHS ---
    NOI_RP_COORDS = os.path.join(BASE_DIR, r"final_indicators\accessibility_munich\null\accessibilities.csv")
    NOI_IMM_B = os.path.join(BASE_DIR,
                             r"final_indicators\noise_munich_ignore_pt_all_activities\run3\noise-analysis\immissions")
    NOI_IMM_A = os.path.join(BASE_DIR,
                             r"final_indicators\noise_altstadt_ignore_pt_all_activities\run3\noise-analysis\immissions")
    NOI_PLANS_B = os.path.join(BASE_DIR,
                               r"eqasim_population_bavaria\final_simulation_output_munich\output_plans.xml.gz")
    NOI_PLANS_A = os.path.join(BASE_DIR,
                               r"eqasim_population_bavaria\final_simulation_output_altstadt\output_plans.xml.gz")
    OUT_NOI = os.path.join(OUT_BASE, r"sociodemo_noise")

    # --- NET WELFARE PATH ---
    OUT_NET = os.path.join(OUT_BASE, r"sociodemo_combined")

    # -----------------------------------------------------------------------
    # 2. EXECUTION CONTROL
    # -----------------------------------------------------------------------
    RUN_ACCESSIBILITY = True
    RUN_ACCIDENTS = True
    RUN_EMISSIONS = True
    RUN_NOISE = True
    RUN_NET_WELFARE = True

    # -----------------------------------------------------------------------
    # 3. PIPELINE EXECUTION
    # -----------------------------------------------------------------------

    if RUN_ACCESSIBILITY :
        print("\n>>> Starting Socio-Demographic ACCESSIBILITY Pipeline...")
        acc_analyzer = AccessibilityAgentAnalyzer(PLANS_BASE, ACC_BEFORE_CSV, ACC_AFTER_CSV, OUT_ACC)
        acc_analyzer.run_pipeline()

    if RUN_ACCIDENTS :
        print("\n>>> Starting Socio-Demographic ACCIDENTS Pipeline...")
        acd_analyzer = AccidentsAgentAnalyzer(NETWORK_XML, ACD_EVENTS_B, ACD_EVENTS_A, PLANS_BASE, OUT_ACD)
        acd_analyzer.run_pipeline()

    if RUN_EMISSIONS :
        print("\n>>> Starting Socio-Demographic EMISSIONS Pipeline...")
        emi_analyzer = EmissionsAgentAnalyzer(EMI_EVENTS_B, EMI_EVENTS_A, PLANS_BASE, OUT_EMI)
        emi_analyzer.run_pipeline()

    if RUN_NOISE :
        print("\n>>> Starting Socio-Demographic NOISE Pipeline...")
        noi_analyzer = NoiseAgentAnalyzer(NOI_RP_COORDS, NOI_IMM_B, NOI_IMM_A, NOI_PLANS_B, NOI_PLANS_A, OUT_NOI)
        noi_analyzer.run_pipeline()

    if RUN_NET_WELFARE :
        print("\n>>> Starting Socio-Demographic NET WELFARE (Consolidated) Pipeline...")
        # Pointing explicitly to the output CSVs generated by the previous steps
        path_acc = os.path.join(OUT_ACC, "accessibility_by_sociodemographic.csv")
        path_acd = os.path.join(OUT_ACD, "accidents_by_sociodemographic.csv")
        path_emi = os.path.join(OUT_EMI, "emissions_by_sociodemographic.csv")
        path_noi = os.path.join(OUT_NOI, "noise_by_sociodemographic.csv")

        net_analyzer = NetWelfareAnalyzer(path_acc, path_acd, path_emi, path_noi, OUT_NET)
        net_analyzer.run_pipeline()

    print("\n" + "=" * 70)
    print("ALL REQUESTED SOCIO-DEMOGRAPHIC PIPELINES EXECUTED SUCCESSFULLY.")
    print("=" * 70)


if __name__ == "__main__" :
    main()